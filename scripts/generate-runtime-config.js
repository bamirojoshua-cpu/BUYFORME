#!/usr/bin/env node
/**
 * Generates css/js/runtime-config.js from environment variables.
 * Falls back to runtime-config.example.js values, then to built-in defaults.
 */
import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const outPath = join(root, "css/js/runtime-config.js");
const examplePath = join(root, "css/js/runtime-config.example.js");

const DEFAULTS = {
  VITE_SUPABASE_URL: "https://jbdfzrgxukwyepwqutdt.supabase.co",
  VITE_SUPABASE_ANON_KEY: "sb_publishable_dkEYDXibAaRL0Lht6D3y6g_Tz9lbxTu",
  VITE_PAYSTACK_PUBLIC_KEY: "pk_test_753e443a4167a0afaa94ce4d0ba2a1c545682e71",
  VITE_STRIPE_PUBLISHABLE_KEY: "",
};

function loadEnvFile() {
  const envPath = join(root, ".env");
  if (!existsSync(envPath)) return;
  const lines = readFileSync(envPath, "utf8").split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = val;
  }
}

function resolve(key) {
  const fromEnv = process.env[key];
  if (fromEnv && !fromEnv.includes("your-")) return fromEnv;
  return DEFAULTS[key] || "";
}

loadEnvFile();

const SUPABASE_URL = resolve("VITE_SUPABASE_URL");
const SUPABASE_ANON_KEY = resolve("VITE_SUPABASE_ANON_KEY");
const PAYSTACK_PUBLIC_KEY = resolve("VITE_PAYSTACK_PUBLIC_KEY");
const STRIPE_PUBLISHABLE_KEY = resolve("VITE_STRIPE_PUBLISHABLE_KEY");

const content = `/* Auto-generated by scripts/generate-runtime-config.js — do not edit manually */
export const SUPABASE_URL = ${JSON.stringify(SUPABASE_URL)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(SUPABASE_ANON_KEY)};
export const PAYSTACK_PUBLIC_KEY = ${JSON.stringify(PAYSTACK_PUBLIC_KEY)};
export const STRIPE_PUBLISHABLE_KEY = ${JSON.stringify(STRIPE_PUBLISHABLE_KEY)};
`;

writeFileSync(outPath, content, "utf8");
console.log("Generated css/js/runtime-config.js");
